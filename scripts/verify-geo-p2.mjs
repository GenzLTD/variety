#!/usr/bin/env node
/**
 * verify-geo-p2.mjs — GEO P2 动态 sitemap + 深层 schema 断言
 *
 * 检查 dist：
 *   - sitemap 仅含有壳路径（9）；禁服务详情 / case-study / pricing 抢跑
 *   - 每条含 lastmod；权威域 .com
 *   - 首页 JSON-LD 含 Service；/contact FAQPage；Breadcrumb
 *   - JSON-LD 禁公开邮箱、sameAs、ICP
 */
import { existsSync, readFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { CORE_SITEMAP_PATHS, SERVICES } from './lib/geo-catalog.mjs'
import { readBookstoreIndexable } from './lib/bookstore-indexable.mjs'

const ROOT = resolve(fileURLToPath(import.meta.url), '..', '..')
const DIR = resolve(ROOT, process.argv.find((a) => a.startsWith('--dir='))?.slice(6) || 'dist')

const errors = []
const ok = (m) => console.log('[geo-p2] ✓ ' + m)
const fail = (m) => {
  errors.push(m)
  console.error('[geo-p2] ✗ ' + m)
}

function read(rel) {
  const p = join(DIR, rel)
  if (!existsSync(p)) {
    fail('缺少 ' + rel)
    return null
  }
  return readFileSync(p, 'utf8')
}

function assertNoInventedContactFacts(label, text) {
  if (!text) return
  const scripts = [...text.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/gi)]
  if (!scripts.length) {
    fail(label + ' 无 JSON-LD script')
    return
  }
  for (const m of scripts) {
    const body = m[1]
    if (/sameAs/i.test(body)) {
      fail(label + ' JSON-LD 含 sameAs（P0 已禁）')
      return
    }
    if (/粤ICP备/i.test(body)) {
      fail(label + ' JSON-LD 含 ICP（.com 未覆盖，禁写入 schema）')
      return
    }
    if (/@szbolent\.com(\.cn)?/i.test(body) || /"email"\s*:/i.test(body)) {
      fail(label + ' JSON-LD 含邮箱字段/地址')
      return
    }
  }
  ok(label + ' JSON-LD 无 sameAs / ICP / 邮箱')
}

const indexBlog = readBookstoreIndexable(DIR).indexable
const expectedPaths = CORE_SITEMAP_PATHS.filter((row) => indexBlog || row.path !== '/blog')
const expectedCount = expectedPaths.length
if (indexBlog) ok('书店有节选，sitemap 收录 /blog')
else ok('书店无节选，sitemap 省略 /blog')
const sitemap = read('sitemap.xml')
if (sitemap) {
  if (!/szbolent\.com/i.test(sitemap)) fail('sitemap 未含 szbolent.com')
  else ok('sitemap 权威域')
  const stripped = sitemap.replace(/@szbolent\.com\.cn/gi, '')
  if (/szbolent\.cn/i.test(stripped)) fail('sitemap 含 szbolent.cn')
  else ok('sitemap 无 .cn 权威残留')
  if (!/generated by scripts\/gen-sitemap\.mjs/i.test(sitemap)) {
    fail('sitemap 缺少 gen-sitemap 生成标记（疑似未跑动态生成）')
  } else ok('sitemap 为动态生成产物')

  const locs = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/gi)].map((m) => m[1])
  if (locs.length !== expectedCount) {
    fail('sitemap URL 数应为有壳 ' + expectedCount + ' 条，实际 ' + locs.length)
  } else ok('sitemap 仅有壳路径 ×' + locs.length)

  const lastmods = [...sitemap.matchAll(/<lastmod>([^<]+)<\/lastmod>/gi)]
  if (lastmods.length !== expectedCount) fail('sitemap lastmod 数不符（' + lastmods.length + ' vs ' + expectedCount + '）')
  else ok('sitemap lastmod ×' + lastmods.length)

  if (!indexBlog && locs.some((u) => /\/blog\/?$/.test(u))) {
    fail('sitemap 在无节选时仍收录 /blog')
  }

  for (const row of expectedPaths) {
    const needle = row.path === '/' ? 'https://szbolent.com/' : 'https://szbolent.com' + row.path
    const hit =
      row.path === '/'
        ? locs.some((u) => u === 'https://szbolent.com/' || u === 'https://szbolent.com')
        : locs.includes(needle)
    if (!hit) fail('sitemap 缺少有壳路径 ' + needle)
    else ok('sitemap 含 ' + row.path)
  }

  for (const svc of SERVICES) {
    const needle = 'https://szbolent.com/services/' + svc.slug
    if (sitemap.includes(needle)) fail('sitemap 抢跑无壳服务详情 ' + needle + '（等 P3 壳）')
  }
  ok('sitemap 未收录无壳 /services/:slug')

  for (const banned of ['/case-study', '/pricing']) {
    if (sitemap.includes('https://szbolent.com' + banned)) {
      fail('sitemap 抢跑无壳/受限路径 ' + banned)
    }
  }
  ok('sitemap 未收录 /case-study、/pricing')
}

const index = read('index.html')
if (index) {
  if (!/"@type"\s*:\s*"Service"/i.test(index)) fail('首页 JSON-LD 缺少 Service')
  else ok('首页含 Service schema')
  if (!/"@type"\s*:\s*"OfferCatalog"/i.test(index)) fail('首页 JSON-LD 缺少 OfferCatalog')
  else ok('首页含 OfferCatalog')
  assertNoInventedContactFacts('index.html', index)
}

const servicesHtml = read('services/index.html')
if (servicesHtml) {
  if (!/"@type"\s*:\s*"BreadcrumbList"/i.test(servicesHtml)) fail('/services 缺少 BreadcrumbList')
  else ok('/services 含 BreadcrumbList')
  if (!/"@type"\s*:\s*"Service"/i.test(servicesHtml)) fail('/services 缺少 Service')
  else ok('/services 含 Service')
  assertNoInventedContactFacts('services/index.html', servicesHtml)
}

const contactHtml = read('contact/index.html')
if (contactHtml) {
  if (!/"@type"\s*:\s*"FAQPage"/i.test(contactHtml)) fail('/contact 缺少 FAQPage')
  else ok('/contact 含 FAQPage')
  if (!/"@type"\s*:\s*"BreadcrumbList"/i.test(contactHtml)) fail('/contact 缺少 BreadcrumbList')
  else ok('/contact 含 BreadcrumbList')
  if (!/当前无公开邮箱/.test(contactHtml) && !/联系页表单/.test(contactHtml)) {
    fail('/contact FAQ/正文未体现「表单联系、无公开邮箱」事实')
  } else ok('/contact 联系事实可读')
  assertNoInventedContactFacts('contact/index.html', contactHtml)
}

const aboutHtml = read('about/index.html')
if (aboutHtml) {
  if (!/"@type"\s*:\s*"BreadcrumbList"/i.test(aboutHtml)) fail('/about 缺少 BreadcrumbList')
  else ok('/about 含 BreadcrumbList')
}

if (!existsSync(join(ROOT, 'scripts', 'gen-sitemap.mjs'))) fail('缺少 scripts/gen-sitemap.mjs')
else ok('gen-sitemap.mjs 存在')

if (errors.length) {
  console.error('[geo-p2] ' + errors.length + ' 项失败 @ ' + DIR)
  process.exit(1)
}
console.log('[geo-p2] 全部通过 @ ' + DIR)
