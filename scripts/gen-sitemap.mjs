#!/usr/bin/env node
/**
 * gen-sitemap.mjs — GEO P2 动态 sitemap
 *
 * 在构建期根据烘焙菜单 + 核心路径 + 服务 slug 写出 sitemap.xml，
 * lastmod 默认取构建日（可用 SITEMAP_LASTMOD=YYYY-MM-DD 覆盖）。
 *
 * 用法：
 *   node scripts/gen-sitemap.mjs                  → dist/sitemap.xml
 *   node scripts/gen-sitemap.mjs --out=public/sitemap.xml
 *   node scripts/gen-sitemap.mjs --check           → 只打印条目数，不写文件
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { SITE, buildSitemapEntries, isoDate } from './lib/geo-catalog.mjs'

const ROOT = resolve(fileURLToPath(import.meta.url), '..', '..')
const CHECK = process.argv.includes('--check')
const outArg = process.argv.find((a) => a.startsWith('--out='))
const OUT = resolve(ROOT, outArg ? outArg.slice('--out='.length) : 'dist/sitemap.xml')
const LASTMOD = process.env.SITEMAP_LASTMOD || isoDate()

function loadMenuItems() {
  const menuPath = join(ROOT, 'src', 'menus', 'szbolent.json')
  if (!existsSync(menuPath)) return []
  try {
    const data = JSON.parse(readFileSync(menuPath, 'utf8'))
    return Array.isArray(data?.items) ? data.items : []
  } catch {
    return []
  }
}

function escapeXml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function locFor(path) {
  if (path === '/') return `${SITE}/`
  return `${SITE}${path}`
}

function render(entries) {
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- generated by scripts/gen-sitemap.mjs — do not hand-edit dist copy -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ]
  for (const e of entries) {
    lines.push('  <url>')
    lines.push(`    <loc>${escapeXml(locFor(e.path))}</loc>`)
    lines.push(`    <lastmod>${escapeXml(LASTMOD)}</lastmod>`)
    lines.push(`    <changefreq>${escapeXml(e.changefreq)}</changefreq>`)
    lines.push(`    <priority>${escapeXml(e.priority)}</priority>`)
    lines.push('  </url>')
  }
  lines.push('</urlset>', '')
  return lines.join('\n')
}

function main() {
  const entries = buildSitemapEntries(loadMenuItems())
  const xml = render(entries)

  if (CHECK) {
    console.log(`[gen-sitemap] ${entries.length} urls @ ${SITE} lastmod=${LASTMOD}`)
    for (const e of entries) console.log(`  ${locFor(e.path)}`)
    return
  }

  mkdirSync(dirname(OUT), { recursive: true })
  writeFileSync(OUT, xml, 'utf8')
  console.log(`[gen-sitemap] wrote ${OUT} (${entries.length} urls, lastmod=${LASTMOD})`)
}

main()
